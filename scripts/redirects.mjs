// Writes public/_redirects (Cloudflare's redirect file) from the redirects in vercel.json, so both hosts send old
// addresses to the same place. Re-run after changing vercel.json. Usage: npm run redirects
//   :name stays a placeholder, :name* becomes a splat, and :lang(ne|hi) is written out once per language.
import { readFileSync, writeFileSync } from 'node:fs';

const { redirects = [] } = JSON.parse(readFileSync('vercel.json', 'utf8'));
const lines = [];
for (const r of redirects) {
  const langs = r.source.match(/:lang\(([^)]+)\)/)?.[1]?.split('|') ?? [undefined];
  for (const lang of langs) {
    const fix = (path) => {
      let out = path.replace(/:lang(\([^)]*\))?/g, lang ?? ':lang');
      out = out.replace(/\/:(\w+)\*/g, '/*');
      return out;
    };
    const source = fix(r.source);
    let destination = r.destination.replace(/:lang/g, lang ?? ':lang');
    // A splat in the source is written :splat in the destination.
    if (source.endsWith('/*')) destination = destination.replace(/:(\w+)\*/g, ':splat');
    lines.push(`${source} ${destination} ${r.permanent ? 301 : 302}`);
  }
}
writeFileSync('public/_redirects', `# Generated by scripts/redirects.mjs from vercel.json. Do not edit by hand.\n${lines.join('\n')}\n`);
console.log(`Wrote public/_redirects with ${lines.length} rules`);
